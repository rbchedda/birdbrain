#!/usr/bin/env node
// Builds the Terrain assets that ship inside the app for French Creek State Park, so
// the Terrain basemap works there with no tile host (R2 is not set up yet) and offline.
//
// Inputs (all public, no account):
//   --pmtiles <file>  Protomaps extract: pmtiles extract https://build.protomaps.com/<YYYYMMDD>.pmtiles
//                     fc.pmtiles --bbox=-75.90,40.15,-75.68,40.28 --maxzoom=15   (ODbL, (c) OpenStreetMap)
//   DEM               fetched here from AWS Terrain Tiles (s3://elevation-tiles-prod, open data), z0-12
//   --glyphs <dir>    output of build-glyphs.mjs (Inter / Barlow Condensed, SIL OFL 1.1); 0-511 + 8192 only
//   --vendor <dir>    npm pack pmtiles@4.5.0 + maplibre-contour@0.1.1 (both BSD-3-Clause), unpacked
//
// Writes app/src/components/map/vendor/terrainLibs.ts and app/src/components/map/frenchCreekTerrain.ts.
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const arg = (k) => { const i = process.argv.indexOf(k); return i > 0 ? process.argv[i + 1] : undefined; };
const BBOX = [-75.9, 40.15, -75.68, 40.28];
const DEM = 'https://s3.amazonaws.com/elevation-tiles-prod/terrarium';
const STACKS = ['Inter Medium', 'Inter Medium Italic', 'Barlow Condensed Bold'];
const RANGES = ['0-255', '256-511', '8192-8447'];
const appMap = new URL('../../app/src/components/map/', import.meta.url).pathname;

const tile = (lng, lat, z) => {
  const n = 2 ** z, la = (lat * Math.PI) / 180;
  return { x: Math.floor(((lng + 180) / 360) * n), y: Math.floor(((1 - Math.log(Math.tan(la) + 1 / Math.cos(la)) / Math.PI) / 2) * n) };
};

const pmtiles = (await readFile(arg('--pmtiles'))).toString('base64');
const dem = {};
for (let z = 0; z <= 12; z++) {
  const a = tile(BBOX[0], BBOX[3], z), b = tile(BBOX[2], BBOX[1], z);
  for (let x = a.x; x <= b.x; x++) for (let y = a.y; y <= b.y; y++) {
    const r = await fetch(`${DEM}/${z}/${x}/${y}.png`);
    if (!r.ok) throw new Error(`DEM ${z}/${x}/${y}: ${r.status}`);
    dem[`${z}/${x}/${y}`] = Buffer.from(await r.arrayBuffer()).toString('base64');
  }
}
const glyphs = {};
for (const s of STACKS) for (const r of RANGES) glyphs[`${s}/${r}`] = (await readFile(join(arg('--glyphs'), s, `${r}.pbf`))).toString('base64');

const head = '// GENERATED by scripts/basemap/bundle-french-creek.mjs. Do not edit.\n';
await writeFile(join(appMap, 'frenchCreekTerrain.ts'), `${head}/* eslint-disable */
// Map data (c) OpenStreetMap contributors, ODbL, via Protomaps. Terrain: 3DEP, GMTED2010, SRTM (USGS) via
// AWS Terrain Tiles (Mapzen). Fonts: Inter, Barlow Condensed (SIL OFL 1.1).
export const FRENCH_CREEK_BBOX = ${JSON.stringify(BBOX)} as const;
export const frenchCreekTerrain = ${JSON.stringify({ pmtiles, dem, glyphs })};
`);
const v = arg('--vendor');
const pm = await readFile(join(v, 'pmtiles-4.5.0/package/dist/pmtiles.js'), 'utf8');
const mc = await readFile(join(v, 'maplibre-contour-0.1.1/package/dist/index.min.js'), 'utf8');
await writeFile(join(appMap, 'vendor/terrainLibs.ts'), `${head}// pmtiles@4.5.0 and maplibre-contour@0.1.1, both BSD-3-Clause (licenses in their npm packages).
export const pmtilesJs = ${JSON.stringify(pm)};
export const contourJs = ${JSON.stringify(mc)};
`);
console.log('dem tiles', Object.keys(dem).length, 'pmtiles bytes', pmtiles.length);
